package com.wanderwildwood.aikotoba.ui

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin writes
 * build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the unit tests
 * compile (it is part of the merged resources the R class comes from).
 */
class LicencesTest {
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val data by lazy {
        LicencesData(
            "aikotoba", SOURCE_URL, "GPL-3.0-only", generated,
            LICENCE_RAW.map { LicenceText(it.first, it.first, it.second) }, emptyList(),
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf(
        "com.mudita:MMD", "app.keemobile:kotpass", "com.lambdapioneer.argon2kt:argon2kt",
        "androidx.camera:camera-core", "com.google.zxing:core", "com.squareup.okio:okio",
        "org.jetbrains.kotlin:kotlin-stdlib",
        "Lato typeface", "Material Symbols icons", "EFF large word list for passphrases",
        "Argon2 reference implementation (native, inside Argon2Kt)", "Calm QR (the scanner)",
        "kAuth (codes and imports)",
    )

    private fun component(id: String) = generated.first { it.note?.startsWith("$id ") == true }

    /** BSD and MIT libraries carry their own license file, copyright line and all. */
    @Test fun mitAndBsdLibrariesCarryTheirOwnText() {
        mapOf(
            "app.keemobile:kotpass" to "Copyright (c) 2021 Denis T.",
            "com.lambdapioneer.argon2kt:argon2kt" to "Copyright (c) Daniel Hugenroth",
            "androidx.camera:camera-core" to "Copyright 2011 The LibYuv Project Authors",
        ).forEach { (id, line) ->
            assertTrue("$id has no own text with \"$line\"", component(id).texts.any { it.content?.contains(line) == true })
        }
    }

    @Test fun mmdIsByMudita() {
        assertEquals("Mudita", component("com.mudita:MMD").author)
    }

    /** Debug-only artifacts (debugImplementation) are not in the release APK, so not on its page. */
    @Test fun noDebugOnlyLibraries() {
        val debugOnly = listOf(
            "androidx.compose.ui:ui-tooling", "androidx.compose.ui:ui-tooling-data",
            "androidx.compose.material:material", "androidx.compose.material:material-icons-core",
        )
        assertEquals(emptyList<String>(), generated.mapNotNull { it.note?.substringBefore(' ') }.filter { it in debugOnly })
    }

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 5)
    }

    @Test fun theDataHasNoProblems() {
        assertEquals(emptyList<String>(), licencesProblems(data))
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/aikotoba", SOURCE_URL)
    }

    @Test fun gplIsFirstAndEveryTextIsBundled() {
        assertEquals("gpl", orderedTexts(data.texts).first().id)
        val raw = File("src/main/res/raw")
        assertTrue(raw.listFiles().orEmpty().count { it.extension == "txt" } >= LICENCE_RAW.size)
        assertTrue(licenceParagraphs(File(raw, raw.list().orEmpty().first { it.contains("gpl") }).readText()).size > 10)
    }
}
